-- Initial database schema derived from docs/initialDatabaseDesign.png
-- auth.users is managed by Supabase Auth (auth_users in domain model).

create type public.building_kind as enum (
  'academic',
  'residence',
  'parking',
  'athletic',
  'dining',
  'chapel',
  'student_life',
  'other'
);

create type public.room_type as enum (
  'classroom',
  'lecture_hall',
  'lab',
  'office',
  'auditorium',
  'study',
  'dining',
  'restroom',
  'facility',
  'lounge'
);

create type public.poi_category as enum (
  'restroom',
  'printer',
  'water fountain',
  'vending machine',
  'elevator',
  'dining',
  'other'
);

create type public.issue_status as enum (
  'open',
  'in_progress',
  'resolved',
  'closed'
);

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  settings jsonb not null default '{}'::jsonb,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.buildings (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  kind public.building_kind not null default 'academic',
  aliases text[] not null default '{}',
  campus_x real,
  campus_y real
);

create table if not exists public.floors (
  id bigint generated by default as identity primary key,
  building_id bigint not null references public.buildings (id) on delete cascade,
  level integer not null,
  label text not null,
  plan_path text,
  plan_width integer,
  plan_height integer,
  unique (building_id, level)
);

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  floor_id bigint not null references public.floors (id) on delete cascade,
  client_room_id text unique,
  room_number text not null,
  name text,
  type public.room_type not null default 'classroom',
  aliases text[] not null default '{}',
  x real,
  y real
);

create table if not exists public.points_of_interest (
  id bigint generated by default as identity primary key,
  category public.poi_category not null,
  label text not null,
  description text not null default '',
  floor_id bigint references public.floors (id) on delete set null,
  x real,
  y real
);

create table if not exists public.favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  building_id bigint references public.buildings (id) on delete cascade,
  room_id bigint references public.rooms (id) on delete cascade,
  poi_id bigint references public.points_of_interest (id) on delete cascade,
  floor_label text,
  created_at timestamptz not null default now(),
  constraint favorites_one_target_check check (
    (building_id is not null)::integer +
    (room_id is not null)::integer +
    (poi_id is not null)::integer = 1
  )
);

create unique index if not exists favorites_user_building_floor_uidx
  on public.favorites (user_id, building_id, coalesce(floor_label, ''))
  where building_id is not null;

create unique index if not exists favorites_user_room_uidx
  on public.favorites (user_id, room_id)
  where room_id is not null;

create unique index if not exists favorites_user_poi_uidx
  on public.favorites (user_id, poi_id)
  where poi_id is not null;

create table if not exists public.issue_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  room_id bigint references public.rooms (id) on delete set null,
  message text not null,
  status public.issue_status not null default 'open',
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.favorites enable row level security;
alter table public.issue_reports enable row level security;

create policy "Users can read own profile"
  on public.profiles for select
  using (auth.uid() = id);

create policy "Users can update own profile"
  on public.profiles for update
  using (auth.uid() = id);

create policy "Users can read own favorites"
  on public.favorites for select
  using (auth.uid() = user_id);

create policy "Users can insert own favorites"
  on public.favorites for insert
  with check (auth.uid() = user_id);

create policy "Users can delete own favorites"
  on public.favorites for delete
  using (auth.uid() = user_id);
